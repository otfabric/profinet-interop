#!/usr/bin/env python3
"""Builds the interoperability matrix from the result files go-profinet's
interop tests write (PROFINET_INTEROP_RESULTS=dir make interop).

usage: matrix.py RESULTS_DIR OUT.json OUT.md
"""
import datetime
import glob
import json
import re
import os
import sys

ROLE_OF_GO = {"device": "IO-Controller", "controller": "IO-Device", "dcp-tool": "DCP responder", "decoder": "-"}


def go_role(role):
    """go-profinet's role against a peer: from the peer's role, or the
    "(go-profinet: ...)" a test writes into it."""
    if role in ROLE_OF_GO:
        return ROLE_OF_GO[role]
    m = re.search(r"\(go-profinet: ([^)]+)\)", role)
    return m.group(1) if m else "-"


def main():
    src, out_json, out_md = sys.argv[1:4]
    results = []
    for f in sorted(glob.glob(os.path.join(src, "*.json"))):
        with open(f) as fh:
            results.append(json.load(fh))
    rows = []
    for r in results:
        for c in r.get("checks", []):
            peer = r.get("peer") or "-"
            if c["feature"].startswith(("scapy decode", "tshark check")):
                peer_row = c["feature"].split()[0]
                role = "decoder"
            else:
                peer_row, role = peer, r.get("role", "")
            rows.append({
                "feature": c["feature"], "peer": peer_row, "peerRole": role,
                "goRole": go_role(role), "image": r.get("image", ""),
                "outcome": c["outcome"], "detail": c.get("detail", ""), "test": r.get("test", ""),
            })
    doc = {"schemaVersion": "1.0", "generated": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"), "rows": rows}
    with open(out_json, "w") as fh:
        json.dump(doc, fh, indent=2)
        fh.write("\n")
    peers = sorted({r["peer"] for r in rows})
    lines = ["<!-- Generated by scripts/matrix.py from go-profinet's interop results; do not edit. -->", "",
             "# Interoperability matrix", "",
             f"Generated {doc['generated']} from {len(results)} test runs. "
             "Outcomes: **pass**, **fail**, **n/a** (the peer does not implement the feature; the detail says why), "
             "**peer-deviation** (the peer deviates from the standard; the detail says how). "
             "Reproduce with `make -C ../go-profinet interop` (see [INTEROPERABILITY.md](INTEROPERABILITY.md)).", "",
             "| Peer | go-profinet role | pass | fail | n/a | peer-deviation |", "|------|------------------|------|------|-----|----------------|"]
    for p in peers:
        pr = [r for r in rows if r["peer"] == p]
        roles = ", ".join(dict.fromkeys(r["goRole"] for r in pr if r["goRole"] != "-")) or "-"
        lines.append(f"| {p} | {roles} | {sum(r['outcome']=='pass' for r in pr)} | {sum(r['outcome']=='fail' for r in pr)} | {sum(r['outcome']=='n/a' for r in pr)} | {sum(r['outcome']=='peer-deviation' for r in pr)} |")
    for p in peers:
        lines += ["", f"## {p}", "", "| Feature | go-profinet role | Outcome | Detail | Test |", "|---------|------------------|---------|--------|------|"]
        for r in [x for x in rows if x["peer"] == p]:
            d = r["detail"].replace("|", "\\|").replace("\n", " ")
            if len(d) > 160:
                d = d[:157] + "..."
            lines.append(f"| {r['feature']} | {r['goRole']} | {r['outcome']} | {d} | `{r['test']}` |")
    with open(out_md, "w") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
